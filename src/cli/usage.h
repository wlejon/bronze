#pragma once

namespace bronze::cli {

constexpr const char* kUsage =
    "bronze — AOT compiler for JavaScript (native-first, Brass backend)\n"
    "\n"
    "Usage:\n"
    "  bronze run <file> [-- <args...>]    Run JS source directly in-memory\n"
    "                                      (takes --host-globals, --classic[=<marker>]:\n"
    "                                      a classic script, its vars and functions globals;\n"
    "                                      exposes the `Bronze` CLI host global)\n"
    "  bronze eval <code> (or -e <code>)   Evaluate JS code directly in-memory\n"
    "  bronze lex <file>                   Tokenize and print one token per line\n"
    "  bronze parse <file>                 Parse and print the canonical AST dump\n"
    "  bronze types <file>                 Infer types and print the canonical type dump\n"
    "  bronze check <file>                 Static symbolic bug-finding check (null-deref,\n"
    "                                      out-of-bounds, nan-poison; takes\n"
    "                                      --deterministic for lockstep replay verification)\n"
    "  bronze prove-equiv <old> <new>      Formally prove equivalence of JS functions\n"
    "                                      using Brass bitvector SMT (takes --fn <name>,\n"
    "                                      --json)\n"
    "  bronze synth-tests <file>           Synthesize path-covering & hazard-reproducing\n"
    "                                      unit tests via symbolic execution (takes\n"
    "                                      -o <out.js>, --json)\n"
    "  bronze il <file>                    Lower to IL, optimise it as `build` does and\n"
    "                                      print the canonical IL dump (takes\n"
    "                                      --lowered for the IL before optimisation)\n"
    "  bronze build <file> -o <output>     Compile JS source to a native program: the\n"
    "                                      executable, the compiled module beside it\n"
    "                                      (<output> with .dll/.so/.dylib in place of\n"
    "                                      its extension) and the shared runtime it\n"
    "                                      loads — on Windows with the C++ runtime\n"
    "                                      DLLs, so the folder runs on a machine\n"
    "                                      without the VC redistributable. No\n"
    "                                      linker is involved.\n"
    "  bronze version                      Print version\n"
    "\n"
    "Options (run, eval):\n"
    "  -g, --debug                         Generate native debug information\n"
    "\n"
    "Options (types, il, build):\n"
    "  --module-root <prefix>=<path>       Map module specifier prefix to a path\n"
    "  --import-map <path>                 Load browser import map JSON file\n"
    "\n"
    "Options (il, build):\n"
    "  --host-globals <path>               Manifest of identifiers an embedding host\n"
    "                                      will register with the runtime before the\n"
    "                                      program runs: one name per line, `#`\n"
    "                                      comments, blank lines ignored. Each joins\n"
    "                                      the provided-globals set, so reads resolve\n"
    "                                      like a builtin's instead of warning and\n"
    "                                      throwing ReferenceError.\n"
    "  --native-manifest <path>            Native manifest (JSON file, or a directory of\n"
    "                                      them) a host printed from its registry with\n"
    "                                      embed::writeNativeManifest. Each entry names a\n"
    "                                      JS path the program calls as a direct native\n"
    "                                      call and its C signature; the module binds\n"
    "                                      them by name from the host's registry when it\n"
    "                                      loads. Nothing is linked.\n"
    "  --feedback-in <file.tfb>            Read a `--harvest-out` inline-cache harvest back.\n"
    "                                      A malformed file is an error. The optimiser's\n"
    "                                      speculation step makes a guarded copy of each\n"
    "                                      function it has decisive evidence for; a failed\n"
    "                                      guard resumes the generic function\n"
    "                                      (src/opt/speculate). A harvest of another build\n"
    "                                      is ignored.\n"
    "  --opt-stats                         Print the optimiser pipeline's counts\n"
    "                                      (speculation, redundancy, representation)\n"
    "                                      to stderr.\n"
    "  --harvest-out <file.tfb>            (build) The program reads its inline caches\n"
    "                                      back at exit as an inline-cache harvest written\n"
    "                                      there.\n"
    "\n"
    "Options (il):\n"
    "  --lowered                           Print the IL as lowered, before the\n"
    "                                      optimiser pipeline runs.\n"
    "\n"
    "Options (build):\n"
    "  -g, --debug                         Emit native debug sections (.debug_* on ELF/Mach-O,\n"
    "                                      .debug$S/.debug$T on Windows COFF)\n"
    "  --timings                           Print per-phase wall time to stderr. The\n"
    "                                      one deliberately nondeterministic thing\n"
    "                                      bronze prints, which is why it is opt-in\n"
    "                                      and on stderr: no pinned output can\n"
    "                                      see it.\n"
    "  --size-report                       Print where the image's bytes go to\n"
    "                                      stderr: sections, each function's code,\n"
    "                                      stack map and pc table by copy (G, $spec,\n"
    "                                      $opt, twin) and by what the spent harvest\n"
    "                                      says of its run (never, entered, hot),\n"
    "                                      the module tables, the largest functions.\n"
    "  -j <n>, --jobs <n>                  Threads for the per-function work of a\n"
    "                                      build (the IL optimiser's redundancy pass\n"
    "                                      and inliner sizing, brass's optimizer\n"
    "                                      passes, instruction selection through\n"
    "                                      emission).\n"
    "                                      Default: every hardware thread; 1: none\n"
    "                                      but this one. The output is byte-identical\n"
    "                                      at any count.\n"
    "  --entry-symbol <name>               Name the object exported entry point\n"
    "                                      (default bronze_main). The entry and the\n"
    "                                      ABI stamp are the only two symbols an\n"
    "                                      object exports, so distinct names here\n"
    "                                      are what let a host link more than one\n"
    "                                      compiled module into one image.\n"
    "  --no-fn-source                      Leave the source text of each function out\n"
    "                                      of the image. It is embedded by default,\n"
    "                                      once per file, because that is what\n"
    "                                      Function.prototype.toString returns and\n"
    "                                      library code reads it: argument names,\n"
    "                                      `class X` sniffing, hook-identity checks.\n"
    "                                      A library-heavy program roughly doubles in\n"
    "                                      size for it, which is what this buys back;\n"
    "                                      a toString of a compiled function then\n"
    "                                      throws a TypeError naming this flag rather\n"
    "                                      than answering [native code], which no\n"
    "                                      caller could tell from a real one.\n"
    "  --emit-obj                          Stop after object emission: -o names the\n"
    "                                      object file, written exactly where given,\n"
    "                                      and no linker runs. The embedding seam —\n"
    "                                      the host build links the object against\n"
    "                                      bronze's runtime and its own code.\n"
    "  --emit-shared                       Write the loadable module (DLL/.so/.dylib)\n"
    "                                      only, with no host beside it: the module\n"
    "                                      imports the SHARED bronze runtime by name\n"
    "                                      and exports the loadable-module contract\n"
    "                                      (src/abi/bronze_abi.h): <entry>,\n"
    "                                      <entry>_abi_fingerprint,\n"
    "                                      <entry>_host_globals and\n"
    "                                      <entry>_native_imports. A host opens it\n"
    "                                      at run time, checks the stamp against the\n"
    "                                      runtime's, and calls the entry. One\n"
    "                                      runtime in the process means one heap, so\n"
    "                                      a module never carries a runtime of its\n"
    "                                      own.\n"
    "  --module-registry                   Publish each non-entry file this program\n"
    "                                      evaluates into the realm's module registry,\n"
    "                                      under its canonical path. A unit compiled\n"
    "                                      LATER in the same realm — a host's test\n"
    "                                      driver against a page it already loaded —\n"
    "                                      then binds these instances instead of\n"
    "                                      compiling a second copy of the file. For an\n"
    "                                      embedding host only; a standalone program\n"
    "                                      is one unit and nothing reads the registry.\n"
    "  --target <arch>-<os>                The machine the object or module is for,\n"
    "                                      with --emit-obj or --emit-shared: one of\n"
    "                                      x64-windows, x64-linux, x64-macos,\n"
    "                                      aarch64-linux, aarch64-macos,\n"
    "                                      aarch64-windows. brass writes the image in\n"
    "                                      process, so no cross toolchain is needed;\n"
    "                                      the module imports THAT machine's shared\n"
    "                                      runtime by name. A program (neither flag)\n"
    "                                      needs its host binary and is this\n"
    "                                      machine's only. A Darwin target may name\n"
    "                                      its minimum OS (aarch64-macos13.0; else\n"
    "                                      MACOSX_DEPLOYMENT_TARGET, else the one\n"
    "                                      bronze was built for), and iOS is\n"
    "                                      aarch64-ios[<version>] or\n"
    "                                      <arch>-ios[<version>]-simulator.\n"
    "\n"
    "TS annotations are untrusted hints. One that inference does not prove is\n"
    "discarded with a warning and the value stays dynamic.\n";

}  // namespace bronze::cli
